def run_unified_report_cli(
    *,
    source_path: Path | str,
    output_dir: Optional[Path | str] = None,
    events_csv: Optional[Path | str] = None,
    zone_file: Optional[Path | str] = None,
    calibration_path: Optional[Path | str] = None,
    schema_path: Optional[Path | str] = None,
    pose_schema_path: Optional[Path | str] = None,
    fps: Optional[float] = None,
    px_per_cm: Optional[float] = None,
    title: Optional[str] = None,
    include_plots: bool = True,
    json_stdout: bool = False,
) -> int:
    """Execute ``annolid-run report`` and return an exit code."""
    try:
        artifacts = build_unified_analysis_report(
            source_path,
            output_dir=output_dir,
            events_csv=events_csv,
            zone_file=zone_file,
            calibration_path=calibration_path,
            schema_path=schema_path,
            pose_schema_path=pose_schema_path,
            fps=fps,
            px_per_cm=px_per_cm,
            title=title,
            include_plots=include_plots,
        )
    except (FileNotFoundError, ValueError, OSError) as exc:
        print(f"[annolid-run] {exc}", file=sys.stderr)
        return 2

    if json_stdout:
        summary_out = {
            "schema": "unified_analysis_report_cli/v1",
            "overall_status": artifacts.payload.get("overall_status"),
            "status_reasons": artifacts.payload.get("status_reasons"),
            "output_dir": str(artifacts.output_dir),
            "html_report": str(artifacts.html_path),
            "markdown_report": str(artifacts.markdown_path),
            "json_report": str(artifacts.json_path),
            "sections_present": [
                k
                for k, v in (artifacts.payload.get("sections") or {}).items()
                if v is not None
            ],
        }
        print(json.dumps(summary_out, indent=2, ensure_ascii=False))
    else:
        print(f"Report title: {artifacts.payload.get('title')}")
        print(
            f"Quality status: {artifacts.payload.get('overall_status')} "
            f"({'; '.join(artifacts.payload.get('status_reasons') or [])})"
        )
        print(f"HTML report:     {artifacts.html_path}")
        print(f"Markdown report: {artifacts.markdown_path}")
        print(f"JSON report:     {artifacts.json_path}")
    return 0
